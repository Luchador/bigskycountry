#!/usr/bin/env python3
"""Reproduce the bundled HYG v4.1 magnitude <= 6.5 star catalog.

Usage: python tools/cook_stars.py /path/to/hygdata_v41.csv
Normal CMake builds use the checked-in output and do not need Python/network.
Data source/license: licenses/HYG.txt. The Sun (HYG 0) is excluded.
"""
import argparse
import csv
import hashlib
import math
from pathlib import Path

SOURCE_SHA256 = 'd9f69fd86bbf90a4e4d52b4c5c53eacfa6dfc0bfdef85bfd94f095e0bebe4ebd'


def color(bv):
    if not bv:
        return (1.0, 1.0, 1.0)
    # Ballesteros (2012), eq. 14: https://arxiv.org/abs/1201.1809
    bv = max(-0.4, min(2.0, float(bv)))
    temperature = 4600 * (1 / (0.92 * bv + 1.7) + 1 / (0.92 * bv + 0.62))
    # Integrate a blackbody against the CIE 1931 analytic fits, eq. 4/table 1
    # of Wyman, Sloan & Shirley (2013), https://jcgt.org/published/0002/02/01/.
    # This is an approximation to observed color, not a measured spectrum.
    lobes = (((0.362, 442.0, 0.0624, 0.0374), (1.056, 599.8, 0.0264, 0.0323),
              (-0.065, 501.1, 0.0490, 0.0382)),
             ((0.821, 568.8, 0.0213, 0.0247), (0.286, 530.9, 0.0613, 0.0322)),
             ((1.217, 437.0, 0.0845, 0.0278), (0.681, 459.0, 0.0385, 0.0725)))
    xyz = [0.0, 0.0, 0.0]
    for wavelength in range(380, 781, 5):
        radiance = (560.0 / wavelength)**5 / math.expm1(1.438776877e7 / (wavelength * temperature))
        for channel, terms in enumerate(lobes):
            xyz[channel] += radiance * sum(a * math.exp(-0.5 * ((wavelength - b) *
                (c if wavelength < b else d))**2) for a, b, c, d in terms)
    x, y, z = xyz
    rgb = (3.2406*x - 1.5372*y - 0.4986*z, -0.9689*x + 1.8758*y + 0.0415*z,
           0.0557*x - 0.2040*y + 1.0570*z)
    peak = max(rgb)
    def display(v):
        v = max(0.0, v / peak)
        return 12.92*v if v <= 0.0031308 else 1.055*v**(1/2.4) - 0.055
    return tuple(display(v) for v in rgb)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] /
                        'shared/data/hyg_v41_stars.inc')
    args = parser.parse_args()
    if hashlib.sha256(args.source.read_bytes()).hexdigest() != SOURCE_SHA256:
        parser.error('Input is not the expected HYG v4.1 CSV (SHA-256 mismatch)')
    lines = ['// Generated by tools/cook_stars.py from HYG v4.1; CC BY-SA 4.0.',
             '// Attribution and modifications: licenses/HYG.txt. Do not edit by hand.']
    count = missing = 0
    with args.source.open(newline='', encoding='utf-8') as source:
        for row in csv.DictReader(source):
            if row['id'] == '0' or not row['mag'] or float(row['mag']) > 6.5:
                continue
            ra, dec, magnitude = math.radians(float(row['ra']) * 15), math.radians(float(row['dec'])), float(row['mag'])
            rgb = color(row['ci'])
            # Magnitudes are logarithmic. Compress flux for the SDR sky while
            # preserving brightness ordering; a literal flux range loses dim stars.
            flux = 10**(-0.4 * magnitude)
            brightness = 1 - math.exp(-1.5 * flux**0.45)
            values = (math.cos(dec)*math.cos(ra), math.cos(dec)*math.sin(ra), math.sin(dec), magnitude, *rgb, brightness)
            if not all(math.isfinite(v) for v in values):
                parser.error('Non-finite star data: ' + row['id'])
            lines.append('{' + ', '.join(f'{v:.8f}f' for v in values) + '}, // HYG ' + row['id'])
            count += 1
            missing += not row['ci']
    if count != 8920 or missing != 40:
        parser.error(f'Unexpected source counts: {count} stars, {missing} missing colors')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{count} stars; {missing} missing color indices use neutral white: {args.output}')


if __name__ == '__main__':
    main()
